"""Pixabay stock photos and clips, cached locally for 24 hours."""

import hashlib
import json
import threading
import time
from pathlib import Path

import httpx

from .config import CACHE_DIR

CACHE = CACHE_DIR / "stock" / "pixabay-search"
PHOTOS = CACHE_DIR / "stock" / "photos"
_lock = threading.Lock()


def search(query: str, key: str, kind: str, orientation: str = "portrait") -> list[dict]:
    if not key:
        raise RuntimeError("Missing PIXABAY_API_KEY in .env.")
    if kind not in ("photos", "videos"):
        raise ValueError("Pixabay media must be photos or videos.")
    # Queries generated by Gemini are English. Pixabay accepts q up to 100 chars.
    query = query.strip()[:100]
    digest = hashlib.sha1(f"{kind}|{orientation}|{query.lower()}".encode()).hexdigest()[:16]
    cache = CACHE / f"{digest}.json"
    with _lock:
        if cache.exists() and time.time() - cache.stat().st_mtime < 86400:
            return json.loads(cache.read_text(encoding="utf-8"))
        params = {"key": key, "q": query, "lang": "en", "per_page": 30, "safesearch": "true"}
        if kind == "photos":
            params.update(image_type="photo", orientation="vertical" if orientation == "portrait" else "horizontal")
        url = "https://pixabay.com/api/" + ("videos/" if kind == "videos" else "")
        for attempt in range(3):
            try:
                response = httpx.get(url, params=params, timeout=30)
            except httpx.TransportError:
                response = None
            if response is not None and response.status_code == 200:
                break
            if response is not None and response.status_code < 500 and response.status_code != 429:
                raise RuntimeError(f"Pixabay API returned HTTP {response.status_code}; check your key.") from None
            if attempt < 2:
                time.sleep(2 * (attempt + 1))
        else:
            status = f"HTTP {response.status_code}" if response is not None else "network error"
            raise RuntimeError(f"Pixabay API unavailable ({status}); try again later.") from None
        try:
            hits = response.json().get("hits", [])
        except (ValueError, AttributeError):
            raise RuntimeError("Pixabay returned an invalid response.") from None
        results = []
        for hit in hits:
            item = {"id": hit["id"], "page": hit.get("pageURL", ""), "provider": "pixabay"}
            if kind == "photos":
                image = hit.get("largeImageURL") or hit.get("webformatURL")
                if image:
                    results.append(dict(item, url=image))
            else:
                files = [v for v in hit.get("videos", {}).values() if v.get("url") and v.get("width") and v.get("height")
                         and (v["height"] > v["width"]) == (orientation == "portrait")]
                if files and hit.get("duration", 0) >= 3:
                    side = "width" if orientation == "portrait" else "height"
                    best = min(files, key=lambda v: abs(v[side] - 1080))
                    results.append(dict(item, url=best["url"], duration=hit["duration"], portrait=orientation == "portrait"))
        cache.parent.mkdir(parents=True, exist_ok=True)
        temporary = cache.with_suffix(".tmp")
        temporary.write_text(json.dumps(results), encoding="utf-8")
        temporary.replace(cache)
        return results


def photo(query: str, used: set, key: str) -> Path | None:
    for item in search(query, key, "photos"):
        if item["id"] in used:
            continue
        target = PHOTOS / f"pixabay-{item['id']}.jpg"
        if not target.exists() or not target.stat().st_size:
            response = httpx.get(item["url"], timeout=60, follow_redirects=True)
            response.raise_for_status()
            target.parent.mkdir(parents=True, exist_ok=True)
            temporary = target.with_name(f"{target.name}.{threading.get_ident()}.part")
            temporary.write_bytes(response.content)
            temporary.replace(target)
        target.with_suffix(".json").write_text(json.dumps({"page": item["page"]}), encoding="utf-8")
        used.add(item["id"])
        return target
    return None
